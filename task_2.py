"""Практическое занятие № 8, вариант 11, задача 2."""

products = {
    "фрукт": "груша",
    "овощ": "морковь",
    "ягода": "малина",
    "напиток": "сок",
    "десерт": "торт",
}

print("Первоначальный словарь:", products)

# Удаляем элемент только при совпадении ключа и значения.
if products.get("фрукт") == "груша":
    del products["фрукт"]
    print("Элемент 'фрукт = груша' удалён.")
else:
    print("Элемент 'фрукт = груша' не найден.")

print("Изменённый словарь:", products)
